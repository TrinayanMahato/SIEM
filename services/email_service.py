import os
import resend
import json
from dotenv import load_dotenv

# Load environment variables from .env file
load_dotenv()

# Configure Resend API Key
resend.api_key = os.getenv("RESEND_API_KEY")

def send_alert_email(payload: dict, to_email: str = "trinayan.mahato1303@gmail.com"):
    """
    Sends an email alert using Resend.
    """
    email_params = {
        "from": "onboarding@resend.dev",
        "to": [to_email],
        "subject": "SIEM Alert Triggered by Elastalert!",
        "html": f"<h3>New SIEM Alert</h3><p>An alert was triggered with the following details:</p><pre>{json.dumps(payload, indent=2)}</pre>"
    }
    email_response = resend.Emails.send(email_params)
    return email_response


