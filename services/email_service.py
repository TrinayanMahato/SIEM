def send_users_block_approval_email(
    usernames: list,
    host_name: str,
    alert_id: int,
    reasoning: str,
    api_base_url: str = "http://127.0.0.1:8000",
    to_email: str = "trinayan.mahato1303@gmail.com"
):
    """
    Human-in-the-loop email for a multi-account attack on a workstation.
    'Yes' locks ALL listed users for 1 hour; 'No' dismisses.
    """
    from urllib.parse import quote
    users_param = quote(",".join(usernames))
    block_url = f"{api_base_url}/action/users-decision?alert_id={alert_id}&users={users_param}&decision=yes"
    dismiss_url = f"{api_base_url}/action/users-decision?alert_id={alert_id}&users={users_param}&decision=no"
    users_html = ", ".join(f"<code>{u}</code>" for u in usernames)

    html = f"""
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: auto; padding: 24px; border: 1px solid #e0e0e0; border-radius: 8px;">
        <h2 style="color: #c0392b;">⚠️ SIEM — Multi-Account Login Attack</h2>
        <p>Failed physical logins were detected against <strong>many accounts</strong> on <code>{host_name}</code>.
        This may be a brute-force / DDoS-style attack.</p>
        <p><strong>Accounts involved:</strong> {users_html}</p>
        <p><strong>Alert ID:</strong> #{alert_id}</p>
        <h3 style="color: #555;">AI Reasoning:</h3>
        <blockquote style="border-left: 4px solid #c0392b; margin: 0; padding: 12px 16px; background: #fff5f5; color: #333;">
            {reasoning}
        </blockquote>
        <p style="margin-top: 24px;">Lock all these accounts for 1 hour?</p>
        <a href="{block_url}" style="display:inline-block; padding: 12px 24px; background-color: #c0392b; color: white; text-decoration: none; border-radius: 6px; font-weight: bold;">
            🚫 Yes, Block All Users (1 hour)
        </a>
        &nbsp;&nbsp;
        <a href="{dismiss_url}" style="display:inline-block; padding: 12px 24px; background-color: #27ae60; color: white; text-decoration: none; border-radius: 6px; font-weight: bold;">
            ✅ No, Dismiss
        </a>
    </div>
    """

    return resend.Emails.send({
        "from": "onboarding@resend.dev",
        "to": [to_email],
        "subject": f"[ACTION REQUIRED] Multi-account login attack on {host_name}",
        "html": html
    })


